#ifndef FOJ_STAGE339_PRIVATE_DDS_BRIDGE_H
#define FOJ_STAGE339_PRIVATE_DDS_BRIDGE_H
/*
 * Owner-only DDS intake glue. No paths, PKG parser, decrypted resources,
 * file I/O, raw texture logs or native GPU commands appear in this module.
 * Unit-tested using generated DDS inputs only.
 */
#include <stddef.h>
#include <stdint.h>
#include "stage336_gpu_copy_plan.h"

typedef struct {
    FojStage332DdsInfo image;
    FojStage336GpuCopyPlan gpu;
} FojStage339Prepared;

/*
 * Inspect a complete classic DDS, size the Stage336 GPU buffers and decode
 * only level-zero RGBA8 into caller-owned memory. GPU layout parameters must
 * come from dkImageLayout getters at the eventual native call site.
 *
 * Caller must keep the input DDS bytes immutable for the duration of this
 * call. On ANY refusal rgba[0..capacity) and *out remain byte-for-byte
 * unchanged. Exclude all overlapping input/output/metadata ranges.
 *
 * All bridge-owned preflight checks run before decoding. A decoder refusal
 * is transactional by the Stage332 contract; after successful decode the
 * bridge has no additional refusal path before committing *out.
 *
 * No GPU proof is generated by this function. The caller must invoke
 * Stage336's native upload and separately verify the sampled framebuffer.
 */
int foj_stage339_prepare_private_dds(
    const uint8_t *dds, size_t dds_len,
    uint8_t *rgba, size_t rgba_capacity,
    uint32_t row_alignment_bytes,
    uint64_t actual_image_layout_bytes,
    uint32_t actual_image_layout_alignment,
    FojStage339Prepared *out);

#endif
