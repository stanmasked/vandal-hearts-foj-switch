#!/usr/bin/env python3
"""Synthetic corruption tests for candidate DDS headers and offset tables.

Exercises the *actual* previous read-only analysis chain on generated bytes.
No commercial FoJ data, decryption, resource import or verified PS3 format.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import struct
import tempfile

from tools.foj_stability_matrix import synthetic_sample, pipeline, FILE_BYTES
from tools.foj_texture_probe import inventory

DDS_BASE = 2048
DDS_SPACING = 256
DDS_SIZE = 160
HEADER_BYTES = 128
SPEC = (4, 8, "little", "ascending", False)

# The expected outcomes below are authored heuristics-regression contracts.
CASES = (
    ("clean", "internally-consistent-for-private-review", 4),
    ("bad-dds-magic", "insufficient-or-ambiguous", 3),
    ("bad-header-size", "insufficient-or-ambiguous", 3),
    ("zero-width", "insufficient-or-ambiguous", 3),
    ("two-broken-headers", "no-table-candidate", 2),
    ("pointer-gap", "no-table-candidate", 4),
    ("unaligned-pointer-word", "insufficient-or-ambiguous", 4),
    ("partial-header-at-end", "insufficient-or-ambiguous", 3),
    ("truncated-last-image", "internally-contradicted", 4),
    ("unknown-fourcc", "insufficient-or-ambiguous", 4),
    ("unaligned-embedded-dds", "internally-consistent-for-private-review", 4),
    ("trailing-container-bytes", "internally-consistent-for-private-review", 4),
)


def _mutate(original: bytes, name: str) -> bytes:
    raw = bytearray(original)
    first = DDS_BASE
    last = DDS_BASE + 3 * DDS_SPACING
    if name in ("clean", "trailing-container-bytes"):
        if name == "trailing-container-bytes":
            raw.extend(b"X" * 17)
    elif name == "bad-dds-magic":
        raw[first:first+4] = b"NOPE"
    elif name == "bad-header-size":
        struct.pack_into("<I", raw, first + 4, 123)
    elif name == "zero-width":
        struct.pack_into("<I", raw, first + 16, 0)
    elif name == "two-broken-headers":
        raw[first:first+4] = b"NOPE"
        raw[first+DDS_SPACING:first+DDS_SPACING+4] = b"NOPE"
    elif name == "pointer-gap":
        raw[128+8:128+12] = b"\xff" * 4
    elif name == "unaligned-pointer-word":
        # The word at 129 is not a valid 4-byte-aligned reference. Keep
        # the next three rows intact; a 3-row run may still be discovered.
        value = DDS_BASE
        raw[128:136] = b"\xff" * 8
        raw[129:133] = value.to_bytes(4, "little")
    elif name == "partial-header-at-end":
        raw = raw[:last+100]
    elif name == "truncated-last-image":
        # Whole 128-byte header, only 4 of 32 BC1 payload bytes.
        raw = raw[:last+HEADER_BYTES+4]
    elif name == "unknown-fourcc":
        raw[first+84:first+88] = b"ZZZZ"
    elif name == "unaligned-embedded-dds":
        # DDS magic may legally be at an arbitrary byte offset inside
        # an unclassified container. This must not be rejected merely
        # because its offset is not divisible by four.
        original_dds = bytes(raw[last:last+DDS_SIZE])
        raw[last:last+DDS_SIZE+1] = b"\xff" * (DDS_SIZE+1)
        raw[last+1:last+1+DDS_SIZE] = original_dds
        struct.pack_into("<I", raw, 128+3*8, last+1)
    else:
        raise ValueError("Unknown synthetic mutation")
    return bytes(raw)


def _result_label(summary: dict) -> str:
    if summary["tables_examined"] == 0:
        return "no-table-candidate"
    if summary["internally_contradicted"]:
        return "internally-contradicted"
    if summary["insufficient_or_ambiguous"]:
        return "insufficient-or-ambiguous"
    if summary["internally_consistent_for_private_review"]:
        return "internally-consistent-for-private-review"
    return "no-table-candidate"


def run_corruption_matrix(cases: tuple = CASES) -> dict:
    if not isinstance(cases, tuple) or not 1 <= len(cases) <= 32:
        raise ValueError("Expected 1..32 synthetic regression cases")
    seen = set()
    observations = []
    with tempfile.TemporaryDirectory(prefix="foj-corruption-") as tmp:
        root = Path(tmp) / "private-synthetic"
        synthetic_sample(root, SPEC)
        baseline = (root / "synthetic.bin").read_bytes()
        if len(baseline) != FILE_BYTES:
            raise RuntimeError("Unexpected fixture size")
        for name, expected, candidate_count in cases:
            if not isinstance(name, str) or name in seen or not name:
                raise ValueError("Invalid or repeated scenario")
            if not isinstance(expected, str) or type(candidate_count) is not int:
                raise ValueError("Invalid expected scenario outcome")
            seen.add(name)
            (root / "synthetic.bin").write_bytes(_mutate(baseline, name))
            scan = inventory(root)
            actual_candidates = len(scan["candidates"])
            triage = pipeline(root)
            actual = _result_label(triage["summary"])
            matches = actual == expected and actual_candidates == candidate_count
            observations.append({
                "scenario": name,
                "expected_observation": expected,
                "actual_observation": actual,
                "expected_candidates": candidate_count,
                "actual_candidates": actual_candidates,
                "table_candidates": triage["summary"]["tables_examined"],
                "matches_expectation": matches,
            })
    return {
        "schema": "foj-synthetic-corruption-matrix-v1",
        "synthetic_only": True,
        "original_foj_asset_verified": False,
        "note": "Generated DDS candidates test heuristics, not real PS3 formats.",
        "cases": observations,
        "summary": {
            "cases": len(observations),
            "matched_expectations": sum(c["matches_expectation"] for c in observations),
            "unexpected": sum(not c["matches_expectation"] for c in observations),
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    report = run_corruption_matrix()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print("Corrupt/incomplete DDS cases:", report["summary"]["cases"],
          "; expected:", report["summary"]["matched_expectations"],
          "; regressions:", report["summary"]["unexpected"])
    return 0 if not report["summary"]["unexpected"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
