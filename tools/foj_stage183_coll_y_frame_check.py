#!/usr/bin/env python3
"""Stage 183: verify NeXium Y / Z input switches the *real* COLL NRO modes.

Both expected frames are independently generated by compiling the exact
portable C renderers used inside the NRO against invented 50x50 fallback
data. Pixel palette histograms permit window-chrome offset, but a static,
black, reversed, or unchanged emulator window cannot satisfy this audit.
This proves emulator behavior only, not a physical Nintendo Switch display.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path

from PIL import Image, ImageChops

SCHEMA = "foj-stage183-nexium-coll-y-mode-roundtrip-v1"
HEAT_CURSOR = (255, 232, 140)
ISO_CURSOR = (255, 224, 118)
SYNTHETIC_MARKER = (231, 94, 86)


def _open(path: Path) -> Image.Image:
    with Image.open(path) as file:
        image = file.convert("RGB")
    if not (800 <= image.width <= 4096 and 500 <= image.height <= 2160):
        raise ValueError("Unexpected emulator or reference frame dimensions")
    return image


def _count_near(colors: Counter, target: tuple[int, int, int], tolerance: int = 4) -> int:
    return sum(n for rgb, n in colors.items()
               if max(abs(rgb[i] - target[i]) for i in range(3)) <= tolerance)


def _palette_agreement(observed: Counter, reference: Counter) -> float:
    # Compare color counts rather than pixel coordinates; X11 window borders
    # can shift the content. Exact source colors give a strong mode signature.
    selected = ((rgb, n) for rgb, n in reference.items() if n >= 20)
    overlap = 0
    total = 0
    for rgb, count in selected:
        total += count
        overlap += min(count, observed[rgb])
    return overlap / total if total else 0.0


def _changed_pixels(a: Image.Image, b: Image.Image) -> int:
    if a.size != b.size:
        raise ValueError("Emulator mode screenshot sizes changed")
    # This intentionally compares screenshots from the same session, so a
    # large difference in rendered content (not titlebar or cursor blink)
    # is required to claim an input-induced visual change.
    difference = ImageChops.difference(a, b)
    return sum(1 for r, g, blue in difference.getdata()
               if max(r, g, blue) > 12)


def verify_mode_roundtrip(
    heat_path: Path, iso_path: Path, restored_path: Path,
    reference_heat_path: Path, reference_iso_path: Path
) -> dict:
    heat, iso, restored = (_open(p) for p in
                           (heat_path, iso_path, restored_path))
    ref_heat, ref_iso = (_open(reference_heat_path), _open(reference_iso_path))
    if ref_heat.size != (1280, 720) or ref_iso.size != (1280, 720):
        raise ValueError("Unexpected generated C reference dimensions")

    heat_count, iso_count, restored_count = (
        Counter(frame.getdata()) for frame in (heat, iso, restored)
    )
    reference_heat = Counter(ref_heat.getdata())
    reference_iso = Counter(ref_iso.getdata())
    scores = [
        (_palette_agreement(counts, reference_heat),
         _palette_agreement(counts, reference_iso))
        for counts in (heat_count, iso_count, restored_count)
    ]
    if (scores[0][0] < 0.40 or scores[1][1] < 0.40 or
        scores[2][0] < 0.40 or
        scores[0][0] < scores[0][1] + 0.12 or
        scores[1][1] < scores[1][0] + 0.12 or
        scores[2][0] < scores[2][1] + 0.12):
        raise ValueError("Guest screenshots do not match the three C-rendered modes")

    def demand_color(counts: Counter, rgb: tuple[int, int, int],
                     minimum: int = 20) -> int:
        matched = _count_near(counts, rgb)
        if matched < minimum:
            raise ValueError("Mode-specific source color or marker absent")
        return matched

    heat_cursor = demand_color(heat_count, HEAT_CURSOR)
    iso_cursor = demand_color(iso_count, ISO_CURSOR)
    restored_cursor = demand_color(restored_count, HEAT_CURSOR)
    marker_counts = [
        demand_color(counts, SYNTHETIC_MARKER, 150)
        for counts in (heat_count, iso_count, restored_count)
    ]
    changed_first = _changed_pixels(heat, iso)
    changed_second = _changed_pixels(iso, restored)
    changed_back = _changed_pixels(heat, restored)
    pixel_count = heat.width * heat.height
    if (changed_first < 10000 or changed_second < 10000 or
        changed_back > max(5000, pixel_count // 50)):
        raise ValueError("Emulated Y/Z button did not switch and restore COLL display")

    return {
        "schema": SCHEMA,
        "provenance": "generated-only-neXium-coll-guest-visual-check",
        "emulator": "NeXium",
        "mode_sequence": ["2d_raw_heatmap", "isometric_raw_data", "2d_raw_heatmap"],
        "emulated_y_default_keyboard_key": "z",
        "reference_renderer": "portable C heatmap and isometric modules",
        "heatmap_matches_host_reference": True,
        "isometric_matches_host_reference": True,
        "heatmap_return_matches_host_reference": True,
        "screenshot_dimensions": list(heat.size),
        "heatmap_reference_overlap": round(scores[0][0], 5),
        "isometric_reference_overlap": round(scores[1][1], 5),
        "returned_reference_overlap": round(scores[2][0], 5),
        "changed_pixels_first_toggle": changed_first,
        "changed_pixels_second_toggle": changed_second,
        "changed_pixels_after_roundtrip": changed_back,
        "mode_cursor_counts": [heat_cursor, iso_cursor, restored_cursor],
        "generated_fallback_marker_counts": marker_counts,
        "physical_switch_execution_verified": False,
        "original_foj_gameplay_verified": False,
        "original_ps3_assets_used": False,
        "physical_gpu_scanout_verified": False,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--heat", required=True, type=Path)
    parser.add_argument("--iso", required=True, type=Path)
    parser.add_argument("--restored", required=True, type=Path)
    parser.add_argument("--reference-heat", required=True, type=Path)
    parser.add_argument("--reference-iso", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    try:
        result = verify_mode_roundtrip(
            args.heat, args.iso, args.restored,
            args.reference_heat, args.reference_iso
        )
        with args.output.open("x", encoding="utf-8") as stream:
            json.dump(result, stream, sort_keys=True, indent=2)
            stream.write("\n")
    except (OSError, ValueError) as error:
        parser.error(str(error))
    print("Three actual NeXium COLL frames match both C references after Y twice; "
          "no physical Switch execution verified")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
